import matter from "gray-matter";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";

/** Total size of the `files` in one entry's source block, in UTF-8 bytes. */
export const SOURCE_FILES_BYTE_CAP = 64 * 1024;

/**
 * Binary detection is two checks, and a file must pass both to be included:
 *
 * 1. an extension allow-list: only extensions listed here are read at all, so
 *    images, fonts, archives and anything unfamiliar are skipped untouched;
 * 2. a NUL-byte check on the contents of an allow-listed file, which catches a
 *    binary that borrowed a text extension.
 */
const TEXT_EXTENSIONS = new Set([
  ".cjs",
  ".css",
  ".cts",
  ".glsl",
  ".html",
  ".js",
  ".json",
  ".jsx",
  ".md",
  ".mjs",
  ".mts",
  ".svg",
  ".ts",
  ".tsx",
  ".txt",
]);

/** Directories that are never part of a sketch's own source. */
const IGNORED_DIRECTORIES = new Set(["node_modules"]);

/** Machine-generated, and never worth reading on a journal page. */
const IGNORED_FILES = new Set(["package-lock.json"]);

export function buildEntries(sourceRoot) {
  const entriesDir = path.join(sourceRoot, "entries");

  if (!existsSync(entriesDir)) {
    throw new Error(`Sketchbook has no entries/ directory at ${entriesDir}.`);
  }

  const published = readdirSync(entriesDir)
    .map((entryFolder) => readEntry(entriesDir, entryFolder))
    .filter((entry) => entry.frontmatter.publish === true)
    .sort((a, b) => {
      const dateCompare = sortKey(b.frontmatter.date).localeCompare(
        sortKey(a.frontmatter.date),
      );

      return (
        dateCompare ||
        sortKey(a.frontmatter.slug).localeCompare(sortKey(b.frontmatter.slug))
      );
    });

  return published.map((entry, index) => toJournalEntry(entry, index));
}

export function copyEntryMedia(entry, publicJournalDir) {
  for (const media of entry.sourceMedia) {
    const relativeSrc = toPublicPath(media.src);
    const source = resolveRelativePath(
      entry.sourceDir,
      media.src,
      `${entry.slug}: media src`,
    );
    const destination = path.join(publicJournalDir, entry.slug, relativeSrc);

    mkdirSync(path.dirname(destination), { recursive: true });
    cpSync(source, destination, {
      force: true,
      recursive: false,
    });
  }
}

/**
 * `sourceMedia` and `sourceDir` only exist to drive copyEntryMedia, and
 * `sourceDir` is an absolute path on the build machine. Strip them here
 * rather than at the copy step so the serialized shape is guaranteed by the
 * function that writes it, not by call order.
 */
export function writeGeneratedFile(entries, { generatedFile }) {
  const published = entries.map((entry) => {
    const copy = { ...entry };

    delete copy.sourceMedia;
    delete copy.sourceDir;

    return copy;
  });
  const generated = `import type { JournalEntry } from "./portfolio";

/**
 * GENERATED by scripts/build-journal.mjs. Do not edit by hand.
 */
export const journalEntries: JournalEntry[] = ${JSON.stringify(published, null, 2)};
`;

  writeFileSync(generatedFile, generated);
}

function readEntry(entriesDir, entryFolder) {
  const entryDir = path.join(entriesDir, entryFolder);
  const markdownPath = path.join(entryDir, "index.md");

  if (!statSync(entryDir).isDirectory() || !existsSync(markdownPath)) {
    return {
      frontmatter: { publish: false },
    };
  }

  const parsed = matter(readFileSync(markdownPath, "utf8"));

  return {
    body: parsed.content.trim(),
    entryDir,
    entryFolder,
    frontmatter: { ...parsed.data, date: normalizeDate(parsed.data.date) },
  };
}

function toJournalEntry(entry, position) {
  const { body, entryDir, entryFolder, frontmatter } = entry;
  const title = requireString(frontmatter.title, `${entryFolder}: title`);
  const description = requireString(
    frontmatter.description,
    `${entryFolder}: description`,
  );
  const date = requireString(frontmatter.date, `${entryFolder}: date`);
  const slug = requireString(frontmatter.slug, `${entryFolder}: slug`);
  const type = requireString(frontmatter.type, `${entryFolder}: type`);
  const mediaItems = Array.isArray(frontmatter.media) ? frontmatter.media : [];
  const index = formatIndex(position);

  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) {
    throw new Error(`${entryFolder}: date must be YYYY-MM-DD.`);
  }

  if (!["image", "code", "mixed"].includes(type)) {
    throw new Error(`${entryFolder}: type must be image, code, or mixed.`);
  }

  const figures = mediaItems.map((media, mediaIndex) =>
    toFigureConfig(entryDir, slug, media, mediaIndex),
  );
  const mediaBlocks = pairIntoGalleries(figures);
  const firstMedia = figures[0]?.media;
  const blocks = [
    {
      type: "description",
      title,
      index,
      body,
    },
    ...mediaBlocks,
  ];

  if (type === "code" || type === "mixed") {
    blocks.push(toSourceBlock(entryDir, entryFolder, frontmatter.sourcePath));
  }

  return {
    sourceMedia: mediaItems,
    sourceDir: entryDir,
    slug,
    title,
    index,
    description,
    ...(firstMedia ? { cardMedia: firstMedia } : {}),
    blocks,
  };
}

/**
 * Pairs consecutive figures into two-up `gallery` blocks, in order. An odd
 * figure at the end stays a `figure` block.
 */
function pairIntoGalleries(figures) {
  const blocks = [];

  for (let i = 0; i < figures.length; i += 2) {
    const [first, second] = figures.slice(i, i + 2);

    blocks.push(
      second
        ? { type: "gallery", items: [first, second] }
        : { type: "figure", ...first },
    );
  }

  return blocks;
}

/**
 * One image as a `DetailFigureConfig`: the shape of a figure block without its
 * `type`, and of each item in a gallery block.
 */
function toFigureConfig(entryDir, slug, media, mediaIndex) {
  const src = requireString(media?.src, `${slug}: media[${mediaIndex}].src`);
  const alt = requireString(media?.alt, `${slug}: media[${mediaIndex}].alt`);
  const source = resolveRelativePath(entryDir, src, `${slug}: media src`);

  if (!existsSync(source) || !statSync(source).isFile()) {
    throw new Error(`${slug}: media file does not exist: ${src}`);
  }

  return {
    media: {
      src: `/journal/${slug}/${toPublicPath(src)}`,
      alt,
      ...(media.caption ? { caption: String(media.caption) } : {}),
    },
    ...(media.caption ? { showCaption: true } : {}),
  };
}

/**
 * The sketch's source, inlined at build time so the entry page can show it
 * without sending visitors to GitHub.
 *
 * `readme` is the sourcePath's own top-level README.md (required). `files` is
 * every other text file beneath sourcePath: no tests, no binaries (see
 * TEXT_EXTENSIONS), sorted by path, capped at SOURCE_FILES_BYTE_CAP in total.
 * The cap counts `files` only; the README is not part of it.
 */
function toSourceBlock(entryDir, entryFolder, sourcePath) {
  const relativeSourcePath = requireString(
    sourcePath,
    `${entryFolder}: sourcePath`,
  );
  const sourceDir = resolveRelativePath(
    entryDir,
    relativeSourcePath,
    `${entryFolder}: sourcePath`,
  );

  if (!existsSync(sourceDir) || !statSync(sourceDir).isDirectory()) {
    throw new Error(`${entryFolder}: sourcePath must resolve to a directory.`);
  }

  const readmeName = readdirSync(sourceDir, { withFileTypes: true }).find(
    (dirent) => dirent.isFile() && /^readme\.md$/i.test(dirent.name),
  )?.name;

  if (!readmeName) {
    throw new Error(`${entryFolder}: sourcePath must contain a README.md.`);
  }

  const files = collectSourceFiles(sourceDir, readmeName);
  const totalBytes = files.reduce((sum, file) => sum + file.bytes, 0);

  if (totalBytes > SOURCE_FILES_BYTE_CAP) {
    const largest = [...files]
      .sort((a, b) => b.bytes - a.bytes)
      .slice(0, 3)
      .map((file) => `${file.path} (${formatKilobytes(file.bytes)})`)
      .join(", ");

    throw new Error(
      `${entryFolder}: source files total ${formatKilobytes(totalBytes)}, ` +
        `over the ${formatKilobytes(SOURCE_FILES_BYTE_CAP)} limit. ` +
        `Largest: ${largest}. Trim the sourcePath folder or move files out of it.`,
    );
  }

  return {
    type: "source",
    readme: readFileSync(path.join(sourceDir, readmeName), "utf8").trim(),
    files: files.map(({ path: filePath, contents }) => ({
      path: filePath,
      contents,
    })),
  };
}

function collectSourceFiles(sourceDir, readmeName) {
  const files = [];

  const walk = (directory) => {
    // Dirent.isFile() and isDirectory() are false for symlinks, so a link can
    // never lead the walk outside the entry.
    for (const dirent of readdirSync(directory, { withFileTypes: true })) {
      const absolute = path.join(directory, dirent.name);

      if (dirent.isDirectory()) {
        if (
          !IGNORED_DIRECTORIES.has(dirent.name) &&
          !dirent.name.startsWith(".")
        ) {
          walk(absolute);
        }

        continue;
      }

      if (!dirent.isFile() || !isSourceFileName(dirent.name)) {
        continue;
      }

      const relative = toPublicPath(path.relative(sourceDir, absolute));

      if (relative === readmeName) {
        continue;
      }

      const buffer = readFileSync(absolute);

      if (buffer.includes(0)) {
        continue;
      }

      files.push({
        path: relative,
        contents: buffer.toString("utf8"),
        bytes: buffer.length,
      });
    }
  };

  walk(sourceDir);

  // Code-point order rather than localeCompare, so the output does not depend
  // on the build machine's locale.
  return files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

function isSourceFileName(name) {
  return (
    TEXT_EXTENSIONS.has(path.extname(name).toLowerCase()) &&
    !IGNORED_FILES.has(name) &&
    !/\.test\.[^.]+$/.test(name)
  );
}

function formatKilobytes(bytes) {
  return `${(bytes / 1024).toFixed(1)} KB`;
}

function normalizeDate(value) {
  if (value instanceof Date && !Number.isNaN(value.getTime())) {
    return value.toISOString().slice(0, 10);
  }

  return value;
}

function sortKey(value) {
  return typeof value === "string" ? value : "";
}

function requireString(value, label) {
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`${label} is required.`);
  }

  return value.trim();
}

function resolveRelativePath(baseDir, relativePath, label) {
  const normalized = toPublicPath(relativePath);

  if (path.isAbsolute(relativePath) || normalized.startsWith("../")) {
    throw new Error(`${label} must be relative and stay within the entry.`);
  }

  const resolved = path.resolve(baseDir, normalized);
  const base = path.resolve(baseDir);

  if (resolved !== base && !resolved.startsWith(`${base}${path.sep}`)) {
    throw new Error(`${label} must stay within the entry.`);
  }

  return resolved;
}

function toPublicPath(value) {
  return String(value).replaceAll("\\", "/").replace(/^\.\/+/, "");
}

function formatIndex(position) {
  return String(position + 1).padStart(3, "0");
}
